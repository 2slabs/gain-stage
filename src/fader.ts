/** dB shown by Live for a fader value. −Infinity at the bottom. */
export function toDb(value: number): number {
  if (value >= KNEE) return (value - UNITY) * 40;
  if (value < FIRST) return -Infinity;
  const x = (value - FIRST) / STEP;
  const i = Math.min(Math.floor(x), LOW.length - 2);
  const t = x - i;
  // The last table point joins the linear part at the knee.
  const next = i + 1 < LOW.length ? LOW[i + 1] : (KNEE - UNITY) * 40;
  return LOW[i] + (next - LOW[i]) * Math.min(t, 1);
}

/** The quietest finite level a fader can show. */
export const MIN_DB = LOW[0];

/** Fader value for a dB level (clamped to the fader's range; −Infinity → 0). */
export function toValue(db: number): number {
  if (db === -Infinity) return 0;
  if (db >= (KNEE - UNITY) * 40) return Math.min(1, UNITY + db / 40);
  if (db <= MIN_DB) return FIRST;
  // LOW is increasing: binary search, then interpolate.
  let lo = 0;
  let hi = LOW.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (LOW[mid] <= db) lo = mid;
    else hi = mid;
  }
  const span = LOW[hi] - LOW[lo];
  const t = span > 0 ? (db - LOW[lo]) / span : 0;
  return FIRST + (lo + t) * STEP;
}
